"""背景虛化 / 背景換色（對標 CapCut、Riverside、Premiere 的人像模式）。

## 能做什麼

主體的逐幀遮罩已經有了（`aivc seg` 寫出來的 `.aivm`，可以用 `aivc text-boxes --text person`
先找框），這裡只做**合成**：主體照舊，背景模糊或換成純色。

## 為什麼不是「整張模糊再貼回主體」

那是最直覺的寫法，也是**會留下光暈**的寫法：高斯核在主體邊緣會把主體的像素吸進背景，
於是主體周圍浮著一圈自己的殘影（頭髮旁邊一圈膚色、深色衣服旁邊一圈黑）。
商業工具看起來乾淨就是因為它們不這樣做。

這裡用 **normalized convolution**（`normalized_blur`）：模糊 `影像 × 背景權重` 與
`背景權重` 兩張，再相除。主體像素的權重是 0，所以它們**完全不參與**模糊的分子與分母 ——
邊緣附近的背景只由真正的背景像素平均出來，結構上不可能產生主體的殘影。
代價是兩次模糊而不是一次，在 720p 上量到的差距見 `plugins/cards/docs/measurements.md`。

## 半徑跟著畫面寬度走

同一個像素半徑在 720p 與 4K 上是完全不同的視覺強度。所以對外的參數是**畫面寬度的百分比**
（`--strength`），換算成像素在 `blur_radius_px`。
"""
